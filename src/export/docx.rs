use std::fs;
use std::io::{BufWriter, Write};
use std::path::{Path, PathBuf};

use docx_rs::{Docx, Paragraph, Run, AlignmentType};
use md5::{Digest, Md5};
use uuid::Uuid;

use crate::export::ExportError;
use crate::scrape::{Chapter, FicMetadata};

/// Generate a Word (.docx) export for the given fic metadata and chapters.
///
/// Title/author/status lines are added as styled paragraphs, chapter content
/// is converted from HTML to plain text (paragraphs become separate docx
/// paragraphs), and the result is packed into a real OOXML zip.
///
/// Returns `(docx_path, md5_hex)`.
pub async fn create_docx(
    meta: &FicMetadata,
    chapters: &[Chapter],
    tmp_dir: &Path,
) -> Result<(PathBuf, String), ExportError> {
    let uuid = Uuid::new_v4();
    let work_dir = tmp_dir.join(uuid.to_string());
    fs::create_dir_all(&work_dir)?;

    // ---- document ---------------------------------------------------------
    let mut doc = Docx::new();

    // Title
    doc = doc.add_paragraph(
        Paragraph::new()
            .align(AlignmentType::Center)
            .size(32)
            .bold()
            .add_run(Run::new().size(32).bold().add_text(&meta.title)),
    );
    // Author
    doc = doc.add_paragraph(
        Paragraph::new()
            .align(AlignmentType::Center)
            .size(24)
            .add_run(Run::new().size(24).italic().add_text(format!("by {}", meta.author))),
    );
    // Stats line
    doc = doc.add_paragraph(
        Paragraph::new()
            .align(AlignmentType::Center)
            .size(18)
            .add_run(Run::new().size(18).add_text(format!(
                "Words: {} | Chapters: {} | Status: {}",
                meta.words, meta.chapters, meta.status
            ))),
    );
    doc = doc.add_paragraph(
        Paragraph::new()
            .align(AlignmentType::Center)
            .size(18)
            .add_run(Run::new().size(18).add_text(format!(
                "Published: {} | Updated: {}",
                format_timestamp(meta.published),
                format_timestamp(meta.updated),
            ))),
    );
    doc = doc.add_paragraph(Paragraph::new()); // spacer

    // Description
    for para in html_to_paragraphs(&meta.desc) {
        doc = doc.add_paragraph(
            Paragraph::new().add_run(Run::new().add_text(para)),
        );
    }

    // Source footer
    doc = doc.add_paragraph(
        Paragraph::new()
            .add_run(Run::new().italic().add_text(format!(
                "Generated by fICHub — {}",
                meta.source
            ))),
    );
    doc = doc.add_paragraph(Paragraph::new()); // spacer

    // ---- chapters ---------------------------------------------------------
    for chapter in chapters {
        doc = doc.add_paragraph(
            Paragraph::new()
                .size(28)
                .bold()
                .add_run(Run::new().size(28).bold().add_text(&chapter.title)),
        );
        doc = doc.add_paragraph(Paragraph::new()); // spacer
        for para in html_to_paragraphs(&chapter.content) {
            doc = doc.add_paragraph(
                Paragraph::new().add_run(Run::new().add_text(para)),
            );
        }
        doc = doc.add_paragraph(Paragraph::new()); // spacer
    }

    // ---- write ------------------------------------------------------------
    let docx_path = work_dir.join("output.docx");
    let file = fs::File::create(&docx_path)?;
    let mut writer = BufWriter::new(file);
    doc.pack(&mut writer).map_err(|e| ExportError::ZipError(e.to_string()))?;
    writer.flush().map_err(|e| ExportError::IoError(e.to_string()))?;

    let data = fs::read(&docx_path)?;
    let md5_hex = Md5::digest(&data)
        .iter()
        .map(|b| format!("{:02x}", b))
        .collect::<String>();

    Ok((docx_path, md5_hex))
}

